CREATE TABLE embarcacao
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome                   VARCHAR(100),
    registro               VARCHAR(20)                             NOT NULL,
    quantidade_tripulantes INTEGER                                 NOT NULL,
    quantidade_passageiros INTEGER                                 NOT NULL,
    ano_fabricacao         INTEGER                                 NOT NULL,
    comprimento            DECIMAL                                 NOT NULL,
    situacao               VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_embarcacao PRIMARY KEY (id)
);

ALTER TABLE embarcacao
    ADD CONSTRAINT uc_embarcacao_registro UNIQUE (registro);